"""Unit tests for scripts/dhw_benchmark/calib_fit.py: the four-node fit and identification checks."""

from __future__ import annotations

from datetime import UTC, datetime, timedelta

import pytest

from dhw_benchmark.calib_fit import (
    PARAMETER_NAMES,
    FitSettings,
    WindowSimulation,
    FourNodeParams,
    fit_four_node,
    identification,
    initial_state,
    cap_stats,
    simulate_window,
)
from dhw_benchmark.calib_heat import heat_input
from dhw_benchmark.inputs import TankRow
from dhw_benchmark.plant import PlantState, step_minute

T0 = datetime(2026, 11, 2, 0, 0, tzinfo=UTC)
M = timedelta(minutes=1)
TRUE = FourNodeParams(
    eps_1=0.5, eps_2=0.6, flow_kw_per_k=1.2, k_a=0.01, k_b=0.02, loss_kw_per_k=0.005, cop_ref=4.2, c1=0.08, c2=-0.12
)
SETTINGS = FitSettings(room_temp_c=18.0, cold_temp_c=12.0, aux_kw=0.05, coil_order="A", lower_node=0)


def _window(params: FourNodeParams, temps: list[float], minutes: int, heating: range, brine: float = 10.0,
            offset: int = 0, settings: FitSettings = SETTINGS) -> list[TankRow]:
    """A window generated by the plant itself with known parameters (no draws).

    The probes are read from the true state; the fit starts from the
    interpolated hidden nodes, as it would on real data.
    """
    plant = params.plant(settings)
    state = PlantState(temps_c=list(temps))
    rows = []
    for i in range(minutes):
        on = i in heating
        row = TankRow(
            ts=T0 + (offset + i) * M, t_top_c=state.temps_c[3], t_lower_c=state.temps_c[settings.lower_node],
            hp_electric_kw=1.65 if on else 0.05, mode="dhw" if on else "idle", compressor_on=on,
            element_kw=0.0, brine_in_c=brine if on else None,
        )
        rows.append(row)
        heat = heat_input(row, settings.aux_kw, state.temps_c, params.cop(), params.law(settings))
        state, _ = step_minute(plant, state, heat, draw_kwh=0.0)
    return rows


def _windows(params: FourNodeParams = TRUE, brines: tuple[float, ...] = (8.0, 11.0, 14.0)) -> list[list[TankRow]]:
    """Two cooling and three heating windows, starting on the interpolated profile."""
    def start(lo: float, top: float) -> list[float]:
        return [lo, lo + (top - lo) / 3, lo + 2 * (top - lo) / 3, top]
    return [
        _window(params, start(28.0, 52.0), 150, range(0)),
        _window(params, start(35.0, 45.0), 150, range(0), offset=1000),
        _window(params, start(30.0, 43.0), 90, range(20, 70), brines[0], offset=2000),
        _window(params, start(25.0, 40.0), 90, range(15, 75), brines[1], offset=3000),
        _window(params, start(33.0, 46.0), 90, range(25, 60), brines[2], offset=4000),
    ]


def test_parameters_map_to_the_two_tank_plant() -> None:
    """90/90/100/100 L, exchange only within each tank, loss split by volume."""
    plant = TRUE.plant(SETTINGS)
    assert plant.volumes_l == pytest.approx([90.0, 90.0, 100.0, 100.0])
    assert [(p.lower, p.upper, p.k_kw_per_k) for p in plant.tank_pairs] == [(0, 1, 0.01), (2, 3, 0.02)]
    assert sum(plant.loss_kw_per_k) == pytest.approx(0.005)
    split = TRUE.plant(FitSettings(18.0, 12.0, 0.05, "A", 0, split_a=1 / 3, split_b=2 / 3))
    assert split.volumes_l == pytest.approx([60.0, 120.0, 400.0 / 3, 200.0 / 3])


def test_initial_state_follows_the_probe_placement() -> None:
    """Central: lower probe in A_low, hidden nodes at one and two thirds. Alternative:
    lower probe in A_high, A_low 2 K below it (not below cold water), B_low halfway."""
    row = TankRow(ts=T0, t_top_c=50.0, t_lower_c=26.0, hp_electric_kw=0.0, mode="idle", compressor_on=False,
                  element_kw=0.0, brine_in_c=None)
    assert initial_state(row, SETTINGS).temps_c == pytest.approx([26.0, 34.0, 42.0, 50.0])
    alt = FitSettings(18.0, 12.0, 0.05, "A", 1)
    assert initial_state(row, alt).temps_c == pytest.approx([24.0, 26.0, 38.0, 50.0])
    cold_row = row.model_copy(update={"t_lower_c": 13.0})
    assert initial_state(cold_row, alt).temps_c[0] == pytest.approx(12.0)


def test_a_window_simulated_with_the_true_parameters_has_no_residual() -> None:
    """Data generated by the plant is reproduced exactly by the same parameters."""
    simulation = simulate_window(_windows()[2], TRUE, SETTINGS)
    assert max(abs(r) for r in simulation.residuals) < 1e-9
    assert simulation.uncapped_cops and all(1.0 <= c <= 8.0 for c in simulation.uncapped_cops)


def test_the_fit_recovers_known_parameters() -> None:
    """From the fixed starts, the multi-start fit returns close to the generating parameters."""
    result = fit_four_node(_windows(), SETTINGS)
    assert result.rmse_k < 0.02
    assert not result.caps.strained
    for name in ("loss_kw_per_k", "cop_ref", "c2"):
        assert getattr(result.params, name) == pytest.approx(getattr(TRUE, name), rel=0.1, abs=0.01), name


def test_a_steep_cop_law_is_capped_and_reported() -> None:
    """A parameter set whose COP exceeds 8 still simulates; the cap share and excess are counted (AL)."""
    steep = FourNodeParams(**{**TRUE.__dict__, "cop_ref": 8.0, "c1": 0.5})
    sims = [simulate_window(_windows()[4], steep, SETTINGS)]
    stats = cap_stats(sims)
    assert stats.minutes == 35
    assert stats.share_high > 0.5 and stats.excess_high_max > 0.0
    assert stats.strained


def test_cap_statistics_count_both_limits() -> None:
    """Shares and excess per limit; ten percent or less is not strained."""
    sims = [WindowSimulation(uncapped_cops=[8.5, 0.8, 4.0, 5.0, 6.0, 7.0, 3.0, 2.0, 4.5, 5.5])]
    stats = cap_stats(sims)
    assert (stats.share_high, stats.share_low) == (0.1, 0.1)
    assert stats.excess_high_max == pytest.approx(0.5) and stats.excess_low_max == pytest.approx(0.2)
    assert stats.strained
    one = cap_stats([WindowSimulation(uncapped_cops=[8.5] + [4.0] * 9)])
    assert one.share_high == 0.1 and not one.strained
    assert cap_stats([]).minutes == 0 and not cap_stats([]).strained


def test_constant_source_temperature_leaves_c1_unidentified() -> None:
    """With the same source temperature in every heating minute, c1 is weak."""
    windows = _windows(brines=(10.0, 10.0, 10.0))
    diagnosis = identification(fit_four_node(windows, SETTINGS, starts=[TRUE]))
    assert "c1" in diagnosis.weak and not diagnosis.identified


def test_no_circuit_effect_collapses_the_coil_parameters() -> None:
    """With c2 = 0 the three coil parameters act through two combinations: one is weak."""
    flat = FourNodeParams(**{**TRUE.__dict__, "c2": 0.0})
    result = fit_four_node(_windows(flat), SETTINGS, starts=[flat], fixed={"c2": 0.0})
    assert set(identification(result).weak) & {"eps_1", "eps_2", "flow_kw_per_k"}


def test_well_excited_data_is_identified() -> None:
    """Varied source temperatures, heating and cooling: the local diagnostic passes."""
    diagnosis = identification(fit_four_node(_windows(), SETTINGS, starts=[TRUE]))
    assert diagnosis.full_rank and diagnosis.identified, diagnosis


def test_a_fully_fixed_parameter_set_is_evaluated_without_fitting() -> None:
    """With every parameter fixed there is nothing to optimise; the set is still evaluated."""
    windows = _windows()[:3]
    result = fit_four_node(windows, SETTINGS, starts=[TRUE], fixed=TRUE.__dict__)
    assert result.free == [] and result.jacobian.shape == (result.jacobian.shape[0], 0)
    assert result.rmse_k < 1e-9


def test_instant_mixing_every_minute_makes_the_exchange_unobservable() -> None:
    """When the coil inverts both tanks every minute, k_a and k_b have no effect (AI)."""
    def uniform(temp: float) -> list[float]:
        return [temp] * 4
    windows = [
        _window(TRUE, uniform(t), 40, range(40), brine, offset=1000 * i)
        for i, (t, brine) in enumerate([(30.0, 8.0), (36.0, 11.0), (42.0, 14.0)])
    ]
    diagnosis = identification(fit_four_node(windows, SETTINGS, starts=[TRUE]))
    assert {"k_a", "k_b"} <= set(diagnosis.weak)


def test_parameter_names_match_the_bounds() -> None:
    """Every parameter has a fit range (plan amendment Q)."""
    from dhw_benchmark.calib_fit import BOUNDS

    assert set(BOUNDS) == set(PARAMETER_NAMES)
