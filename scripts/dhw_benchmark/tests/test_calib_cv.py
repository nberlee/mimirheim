"""Unit tests for scripts/dhw_benchmark/calib_cv.py: leave-one-ISO-week-out validation and labels."""

from __future__ import annotations

from datetime import UTC, datetime, timedelta

import pytest

from dhw_benchmark.calib_cv import (
    Acceptance,
    CvResult,
    FoldResult,
    choose_coil_order,
    cross_validate,
    fold_plan,
    label,
)
from dhw_benchmark.calib_fit import Diagnosis, FitSettings, FourNodeParams
from dhw_benchmark.calib_heat import heat_input
from dhw_benchmark.inputs import TankRow
from dhw_benchmark.plant import PlantState, step_minute

MONDAY = datetime(2026, 11, 2, 0, 0, tzinfo=UTC)  # ISO week 2026-W45
M = timedelta(minutes=1)
TRUE = FourNodeParams(
    eps_1=0.5, eps_2=0.6, flow_kw_per_k=1.2, k_a=0.01, k_b=0.02, loss_kw_per_k=0.005, cop_ref=4.2, c1=0.08, c2=-0.12
)
SETTINGS = FitSettings(room_temp_c=18.0, cold_temp_c=12.0, aux_kw=0.0, coil_order="A", lower_node=0)
SMALL = Acceptance(min_heating=2, min_cooling=1, min_folds=3)


def _window(start: datetime, lo: float, top: float, minutes: int, heating: range, brine: float) -> list[TankRow]:
    """A draw-free window generated by the plant with TRUE parameters (aux 0.05 kW)."""
    plant = TRUE.plant(SETTINGS)
    state = PlantState(temps_c=[lo, lo + (top - lo) / 3, lo + 2 * (top - lo) / 3, top])
    rows = []
    for i in range(minutes):
        on = i in heating
        row = TankRow(
            ts=start + i * M, t_top_c=state.temps_c[3], t_lower_c=state.temps_c[0],
            hp_electric_kw=1.65 if on else 0.05, mode="dhw" if on else "idle", compressor_on=on,
            element_kw=0.0, brine_in_c=brine if on else None,
        )
        rows.append(row)
        heat = heat_input(row, 0.05, state.temps_c, TRUE.cop(), TRUE.law(SETTINGS))
        state, _ = step_minute(plant, state, heat, draw_kwh=0.0)
    return rows


def _week(week: int) -> tuple[list[list[TankRow]], list[list[TankRow]]]:
    """Two heating windows and one 70-minute cooling window in the given week offset."""
    base = MONDAY + timedelta(weeks=week)
    heating = [
        _window(base + timedelta(hours=2), 30.0, 43.0, 40, range(5, 30), 8.0 + week),
        _window(base + timedelta(days=2), 26.0, 41.0, 40, range(5, 35), 11.0),
    ]
    cooling = [_window(base + timedelta(days=4), 30.0, 50.0, 70, range(0), 10.0)]
    return heating, cooling


def _data(weeks: int = 4) -> tuple[list[list[TankRow]], list[list[TankRow]]]:
    heating, cooling = [], []
    for w in range(weeks):
        h, c = _week(w)
        heating += h
        cooling += c
    return heating, cooling


def test_a_held_out_week_never_enters_its_own_training_set() -> None:
    """Folds by ISO week; a training window touching the held-out week is dropped as well."""
    heating, cooling = _data(3)
    # A cooling window from Sunday evening of week 0 into Monday of week 1.
    straddle = _window(MONDAY + timedelta(days=6, hours=23, minutes=30), 30.0, 50.0, 60, range(0), 10.0)
    plan = fold_plan(heating, cooling + [straddle])
    assert [f.week for f in plan] == [(2026, 45), (2026, 46), (2026, 47)]
    fold = plan[1]
    test_minutes = {r.ts for w in fold.test_heating + fold.test_cooling for r in w}
    train_minutes = {r.ts for w in fold.train_heating + fold.train_cooling for r in w}
    assert not test_minutes & train_minutes
    assert all(r.ts.isocalendar()[:2] != (2026, 46) for w in fold.train_heating + fold.train_cooling for r in w)
    assert straddle in plan[0].test_cooling
    assert straddle not in plan[1].train_cooling and straddle not in plan[1].test_cooling


def test_perfect_data_passes_with_near_zero_held_out_error() -> None:
    """Data generated by the model is predicted on every held-out week."""
    heating, cooling = _data(4)
    rows = [r for w in heating + cooling for r in w]
    cv = cross_validate(rows, heating, cooling, SETTINGS, starts=[TRUE], acceptance=SMALL)
    assert cv.usable_folds == 4 and cv.accepted
    assert cv.heating_top_mae_k < 0.05 and cv.cooling_top_mae_k < 0.05
    assert all(f.aux_kw == pytest.approx(0.05) for f in cv.folds)


def test_a_fold_without_enough_training_windows_is_skipped() -> None:
    """Too few training windows skip the fold; fewer than three usable folds fail acceptance."""
    heating, cooling = _data(3)
    rows = [r for w in heating + cooling for r in w]
    strict = Acceptance(min_heating=5, min_cooling=1, min_folds=3)
    cv = cross_validate(rows, heating, cooling, SETTINGS, starts=[TRUE], acceptance=strict)
    assert cv.usable_folds == 0 and not cv.accepted
    assert all(f.skipped_reason for f in cv.folds)


def test_labels_combine_prediction_and_the_local_diagnostic() -> None:
    """Accepted and identified: conditional; accepted with weak parameters: predictive only;
    failed prediction: not identified."""
    good = Diagnosis(names=["c1"], full_rank=True, condition_number=10.0, weak=[])
    weak = Diagnosis(names=["c1"], full_rank=True, condition_number=10.0, weak=["c1"])
    heating, cooling = _data(4)
    rows = [r for w in heating + cooling for r in w]
    passed = cross_validate(rows, heating, cooling, SETTINGS, starts=[TRUE], acceptance=SMALL)
    assert label(passed, good) == "conditional on the listed assumptions"
    assert label(passed, weak) == "predictive only"
    failed = cross_validate(rows, heating, cooling, SETTINGS, starts=[TRUE],
                            acceptance=Acceptance(min_heating=7, min_cooling=1, min_folds=3))
    assert label(failed, good) == "not identified"


def test_acceptance_thresholds_are_two_and_one_kelvin() -> None:
    """Heating top-probe MAE at most 2 K, cooling at most 1 K (C, AD)."""
    acc = Acceptance()
    assert (acc.heating_mae_k, acc.cooling_mae_k, acc.min_heating, acc.min_cooling, acc.min_folds) == (2.0, 1.0, 8, 3, 3)


def _cv(top: list[float]) -> CvResult:
    """A result with one used fold holding the given heating top residuals."""
    return CvResult(folds=[FoldResult(week=(2026, 45), heating_top=top, cooling_top=[])], acceptance=SMALL)


def test_the_coil_order_with_the_lower_pooled_error_is_central() -> None:
    """Lower pooled top-probe MAE wins; a tie goes to order A; no held-out minutes lose."""
    assert choose_coil_order({"A": _cv([0.5, -0.5]), "B": _cv([0.2, -0.2])}) == "B"
    assert choose_coil_order({"B": _cv([0.3]), "A": _cv([-0.3])}) == "A"
    assert choose_coil_order({"A": _cv([]), "B": _cv([1.0])}) == "B"


def test_a_window_type_without_held_out_minutes_cannot_pass() -> None:
    """No held-out cooling minutes: the pooled cooling MAE is undefined and acceptance fails."""
    cv = CvResult(folds=[FoldResult(week=(2026, w), heating_top=[0.1], cooling_top=[]) for w in (45, 46, 47)],
                  acceptance=SMALL)
    assert cv.usable_folds == 3 and not cv.accepted


def test_a_test_window_spilling_into_the_next_week_excludes_overlapping_training_minutes() -> None:
    """A Sunday-night test window runs into Monday: a Monday training window sharing those
    minutes is dropped, and the spillover minutes do not feed the fold's aux estimate."""
    heating, cooling = _data(3)
    sunday = _window(MONDAY + timedelta(days=6, hours=23, minutes=30), 30.0, 50.0, 70, range(0), 10.0)
    monday = _window(MONDAY + timedelta(days=7, minutes=20), 30.0, 50.0, 60, range(0), 10.0)
    plan = fold_plan(heating, cooling + [sunday, monday])
    week0 = plan[0]
    assert sunday in week0.test_cooling
    assert monday not in week0.train_cooling
    assert monday in plan[1].test_cooling


def test_each_fold_estimates_aux_from_its_own_training_minutes() -> None:
    """Idle power differs per week; each fold's aux is the median outside its held-out minutes."""
    from dhw_benchmark.calib_heat import estimate_aux_kw

    heating, cooling = _data(4)
    idle = {0: 0.03, 1: 0.05, 2: 0.07, 3: 0.09}

    def shift(window: list[TankRow], week: int) -> list[TankRow]:
        return [r if r.compressor_on else r.model_copy(update={"hp_electric_kw": idle[week]}) for r in window]

    heating = [shift(w, i // 2) for i, w in enumerate(heating)]
    cooling = [shift(w, i) for i, w in enumerate(cooling)]
    rows = [r for w in heating + cooling for r in w]
    cv = cross_validate(rows, heating, cooling, SETTINGS, starts=[TRUE], acceptance=SMALL)
    plan = fold_plan(heating, cooling)
    for fold, result in zip(plan, cv.folds, strict=True):
        held = fold.test_minutes
        expected, _ = estimate_aux_kw([r for r in rows if r.ts.isocalendar()[:2] != fold.week and r.ts not in held])
        assert result.aux_kw == pytest.approx(expected)
    assert len({round(f.aux_kw, 6) for f in cv.folds}) > 1


def test_a_minute_invalid_under_the_fold_aux_splits_its_window() -> None:
    """hp - element = 0.09 kW is valid with aux 0.05 but invalid with aux 0.20 (B)."""
    from dhw_benchmark.calib_cv import split_invalid

    window = _window(MONDAY, 30.0, 43.0, 20, range(5, 15), 10.0)
    window[8] = window[8].model_copy(update={"hp_electric_kw": 0.09})
    pieces, invalid = split_invalid([window], 0.05)
    assert invalid == 0 and pieces == [[window]]
    pieces, invalid = split_invalid([window], 0.20)
    assert invalid == 1
    assert pieces == [[window[:9], window[9:]]]


def test_every_fold_fits_from_the_fixed_default_starts(monkeypatch: pytest.MonkeyPatch) -> None:
    """Fold isolation (AM): without explicit starts, each fold receives exactly STARTS."""
    from dhw_benchmark import calib_cv
    from dhw_benchmark.calib_fit import STARTS

    seen = []

    def record(windows: object, settings: object, starts: object, fixed: object) -> object:
        seen.append(list(starts))
        from types import SimpleNamespace
        return SimpleNamespace(params=TRUE)

    monkeypatch.setattr(calib_cv, "fit_four_node", record)
    heating, cooling = _data(4)
    rows = [r for w in heating + cooling for r in w]
    cross_validate(rows, heating, cooling, SETTINGS, acceptance=SMALL)
    assert len(seen) == 4 and all(s == list(STARTS) for s in seen)


def test_held_out_errors_are_pooled_over_minutes_not_averaged_over_folds() -> None:
    """One fold with a single 0 K residual and one with 99 residuals of 2 K pool to 1.98 K."""
    folds = [FoldResult(week=(2026, 45), heating_top=[0.0], cooling_top=[]),
             FoldResult(week=(2026, 46), heating_top=[2.0] * 99, cooling_top=[])]
    assert CvResult(folds=folds, acceptance=SMALL).heating_top_mae_k == pytest.approx(1.98)


def test_a_heating_window_without_a_surviving_heating_step_is_dropped() -> None:
    """If every compressor minute is invalid under the fold aux, the padding left over is
    not heating evidence: the window neither counts nor is scored as heating."""
    from dhw_benchmark.calib_cv import split_invalid

    window = _window(MONDAY, 30.0, 43.0, 20, range(5, 15), 10.0)
    broken = [r.model_copy(update={"hp_electric_kw": 0.09}) if r.compressor_on else r for r in window]
    kept, invalid = split_invalid([broken], 0.20, heating=True)
    assert invalid == 10 and kept == []
    kept, _ = split_invalid([broken], 0.20)
    assert kept  # as a plain window the idle pieces survive


def test_spillover_minutes_do_not_feed_the_fold_aux() -> None:
    """A test window's Monday spillover idles at 0.5 kW: it would move the median if counted."""
    from dhw_benchmark.calib_cv import Fold, fold_aux

    sunday = _window(MONDAY + timedelta(days=6, hours=23, minutes=30), 30.0, 50.0, 130, range(0), 10.0)
    sunday = [r.model_copy(update={"hp_electric_kw": 0.5}) for r in sunday]  # 100 minutes on Monday
    other = _window(MONDAY + timedelta(days=9), 30.0, 50.0, 60, range(0), 10.0)  # 60 minutes at 0.05
    fold = Fold(week=(2026, 45), train_heating=[], train_cooling=[other], test_heating=[], test_cooling=[sunday])
    aux, flagged = fold_aux(fold, sunday + other)
    assert aux == pytest.approx(0.05) and not flagged
